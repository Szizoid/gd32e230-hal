// The bound is what restricts N to the five channels that have an impl.
#[allow(private_bounds)]
impl<const N: u8> Channel<N>
where
    Channel<N>: ChannelOps,
{
    /// Starts a memory-to-peripheral transfer, moving `buf` into `periph`.
    ///
    /// All three are taken by value and come back from [`Transfer::wait`]. The
    /// transfer width follows from the peripheral's word type, so `buf` must
    /// match it.
    pub fn write_to<P: DmaDst<N>>(
        mut self,
        mut periph: P,
        buf: &'static [P::Word],
        prio: Prio,
    ) -> Transfer<N, P, &'static [P::Word]> {
        self.set_maddr(buf.as_ptr() as u32);
        self.set_paddr(periph.addr());
        self.set_cnt(buf.len() as u16);
        self.configure(Dir::M2P, <P::Word as DmaWord>::WIDTH, prio);
        self.set_enabled(true);
        periph.enable_dma();
        Transfer {
            channel: self,
            periph,
            buf,
        }
    }
    /// Starts a peripheral-to-memory transfer, filling `buf` from `periph`.
    ///
    /// All three are taken by value and come back from [`Transfer::wait`], so
    /// `buf` cannot be read before the transfer completes. The transfer width
    /// follows from the peripheral's word type, so `buf` must match it.
    pub fn read_from<P: DmaSrc<N>>(
        mut self,
        mut periph: P,
        buf: &'static mut [P::Word],
        prio: Prio,
    ) -> Transfer<N, P, &'static mut [P::Word]> {
        self.set_maddr(buf.as_mut_ptr() as u32);
        self.set_paddr(periph.addr());
        self.set_cnt(buf.len() as u16);
        self.configure(Dir::P2M, <P::Word as DmaWord>::WIDTH, prio);
        self.set_enabled(true);
        periph.enable_dma();
        Transfer {
            channel: self,
            periph,
            buf,
        }
    }
}

/// A DMA transfer in progress, started by [`Channel::write_to`] or
/// [`read_from`](Channel::read_from).
///
/// Owns the channel, the peripheral and the buffer for as long as the transfer
/// runs; [`wait`](Transfer::wait) is the only way to get them back.
///
/// Dropping instead of waiting stops the transfer and loses all three parts.
// The bounds sit on the declaration only because `Drop` demands it: a `Drop` impl
// may not require more than the type it drops.
#[allow(private_bounds)]
pub struct Transfer<const N: u8, P, BUF>
where
    Channel<N>: ChannelOps,
    P: DmaPeriph<N>,
{
    channel: Channel<N>,
    periph: P,
    buf: BUF,
}

// The bound is what restricts N to the five channels that have an impl.
#[allow(private_bounds)]
impl<const N: u8, P, BUF> Transfer<N, P, BUF>
where
    Channel<N>: ChannelOps,
    P: DmaPeriph<N>,
{
    /// Blocks until the transfer completes, then returns the channel, the
    /// peripheral and the buffer.
    ///
    /// Does not check `ERRIF` — see the DMA entry in the project's conscious
    /// refusals for why a bus error is unreachable through this API.
    pub fn wait(mut self) -> (Channel<N>, P, BUF) {
        while !self.channel.is_complete() {}
        self.periph.disable_dma();
        self.channel.set_enabled(false);
        self.channel.clear_flags();
        // The parts are read out rather than moved out, because a type with a
        // `Drop` impl cannot be taken apart. `ManuallyDrop` is what makes the
        // duplicated ownership sound: the originals are never dropped, never
        // used again, and go out of scope with this expression.
        let transfer = ManuallyDrop::new(self);
        unsafe {
            (
                ptr::read(&transfer.channel),
                ptr::read(&transfer.periph),
                ptr::read(&transfer.buf),
            )
        }
    }
    /// How many transfers the channel has left, without waiting for it.
    ///
    /// Counts transfers, not bytes: at [`Width::Bits16`] a unit is two bytes on
    /// the wire. A snapshot only — the hardware keeps counting while the caller
    /// looks at it, so it serves progress reporting, not deciding that part of
    /// the buffer is safe to touch.
    pub fn remaining(&self) -> u16 {
        self.channel.cnt()
    }
    /// Whether the channel has raised `ERRIF`, having hit a bus error.
    ///
    /// Diagnostics, not an obligation: every address this API can hand a channel
    /// comes from a typed source, so nothing safe aims it at memory that faults.
    /// Useful next to [`remaining`](Transfer::remaining) to tell a stalled
    /// channel from a failed one.
    pub fn is_error(&self) -> bool {
        self.channel.is_error()
    }
}

#[allow(private_bounds)]
impl<const N: u8, P, BUF> Drop for Transfer<N, P, BUF>
where
    Channel<N>: ChannelOps,
    P: DmaPeriph<N>,
{
    /// Stops the transfer where it stands, without waiting for it to finish.
    ///
    /// The tail of [`wait`](Transfer::wait) without the blocking: a running
    /// channel is cut off mid-buffer. Correctness never rested on this — the
    /// buffer is `'static`, and `Drop` is not guaranteed to run anyway.
    fn drop(&mut self) {
        self.periph.disable_dma();
        self.channel.set_enabled(false);
        self.channel.clear_flags();
    }
}

/// The DMA channels, as handed out by [`DmaExt::split`].
#[allow(missing_docs)]
pub struct Channels {
    pub ch0: Channel<0>,
    pub ch1: Channel<1>,
    pub ch2: Channel<2>,
    pub ch3: Channel<3>,
    pub ch4: Channel<4>,
}

/// Splits the DMA peripheral into its individual channels.
pub trait DmaExt {
    /// The channels this peripheral hands out.
    type Channels;

    /// Switches the DMA clock on and hands out the channels.
    ///
    /// Consumes the peripheral, so the channels it returns are the only ones
    /// that will ever exist.
    fn split(self, rcu: &mut Rcu) -> Self::Channels;
}

impl DmaExt for pac::Dma {
    type Channels = Channels;
    fn split(self, rcu: &mut Rcu) -> Self::Channels {
        <pac::Dma as crate::rcu::Enable>::enable(rcu);
        Channels {
            ch0: Channel {
                _marker: PhantomData,
            },
            ch1: Channel {
                _marker: PhantomData,
            },
            ch2: Channel {
                _marker: PhantomData,
            },
            ch3: Channel {
                _marker: PhantomData,
            },
            ch4: Channel {
                _marker: PhantomData,
            },
        }
    }
}
